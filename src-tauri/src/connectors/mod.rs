fn validate_live_provider_set(
    set: &LiveProviderArtifactSet,
    allowed_profiles: &[&str],
) -> Result<(), DiscoveryError> {
    if set.schema_version != LIVE_PROVIDER_ARTIFACT_SET_SCHEMA
        || set.capture_id.is_empty()
        || set.capture_id.len() > 128
        || !set
            .capture_id
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
        || set.operation.is_empty()
        || set.operation.len() > 128
        || set.operation.chars().any(char::is_control)
        || !allowed_profiles.contains(&set.profile.as_str())
        || set.pages.is_empty()
        || set.pages.len() > MAX_LIVE_PROVIDER_PAGES
    {
        return Err(DiscoveryError::Connector(
            "live provider artifact set is malformed or outside limits".into(),
        ));
    }
    for (index, page) in set.pages.iter().enumerate() {
        if usize::from(page.sequence) != index + 1
            || page.operation.is_empty()
            || page.operation.len() > 128
            || page.operation.chars().any(char::is_control)
            || !(100..=599).contains(&page.http_status)
            || (page.parser_eligible && !(200..300).contains(&page.http_status))
            || page.artifact.profile != set.profile
            || page.artifact.observed_at != set.observed_at
        {
            return Err(DiscoveryError::Connector(
                "live provider artifact page manifest is malformed".into(),
            ));
        }
    }
    Ok(())
}

