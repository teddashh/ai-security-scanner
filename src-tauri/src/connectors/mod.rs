//! Source connector registry for preserved, backend-owned discovery snapshots.
//!
//! These connectors deliberately do not contain provider clients. They consume
//! bounded source responses already written into the case artifact store. This
//! keeps discovery attributable and makes connected-but-empty results honest:
//! no connector claims live or organization-wide visibility it did not have.

